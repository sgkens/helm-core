const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const syntaxHighlight = require("@11ty/eleventy-plugin-syntaxhighlight");
const { EleventyHtmlBasePlugin } = require("@11ty/eleventy");
const registerHelmGrammar = require("./helm-prism.js");
const { exampleId, isCompleteExample } = require("./scripts/extract-examples.js");
const { hardwareProfile } = require("./profile-hardware.js");
const blockIcons = require("./_data/blockIcons.json");

const REPO_ROOT = path.resolve(__dirname, "..");

module.exports = function (eleventyConfig) {
  const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[char]));

  function blockIconMarkup(name, assetBase = "/assets/") {
    const icon = blockIcons[name];
    if (!icon) return escapeHtml(name);
    const filePage = `https://spaceengineers.wiki.gg/wiki/File:${encodeURIComponent(icon.file.replaceAll(" ", "_"))}`;
    return `<span class="block-ref block-ref-${icon.tone}"><a href="${filePage}" target="_blank" rel="noopener" title="Icon source: Official Space Engineers Wiki"><img src="${assetBase}blocks/${icon.slug}.png" alt="" width="32" height="32" loading="lazy"></a><span>${escapeHtml(name)}</span></span>`;
  }

  // Plugins
  eleventyConfig.addPlugin(syntaxHighlight, {
    init({ Prism }) {
      registerHelmGrammar(Prism);
    },
  });
  // Rewrites root-relative URLs with pathPrefix (GitLab Pages serves project sites under /<project>/)
  eleventyConfig.addPlugin(EleventyHtmlBasePlugin);

  // The repo lives on /mnt/g (drvfs), where inotify events are unreliable; poll for changes instead.
  eleventyConfig.setChokidarConfig({ usePolling: true, interval: 500 });

  // Fenced ```mermaid blocks become <pre class="mermaid"> for client-side rendering
  // (the syntax highlighter has no mermaid grammar and would leave the text unescaped).
  eleventyConfig.amendLibrary("md", (md) => {
    const fence = md.renderer.rules.fence;
    md.renderer.rules.fence = (tokens, idx, options, env, self) => {
      const token = tokens[idx];
      if (token.info.trim() === "mermaid") {
        return `<pre class="mermaid">${md.utils.escapeHtml(token.content)}</pre>\n`;
      }
      const html = fence(tokens, idx, options, env, self);
      // Complete ```helm examples get a live preview from the frames exported by tools/spritedump.
      if (token.info.trim().split(/\s+/)[0] === "helm" && isCompleteExample(token.content)) {
        const profile = hardwareProfile((token.content.match(/^profile:\s*([^\s#]+)/im) || [])[1]);
        return html + `<div class="hv hv-medium not-prose" data-helm-viz data-layout="${exampleId(token.content)}" data-profile="${profile}"></div>\n`;
      }
      return html;
    };
  });

  // Passthroughs
  eleventyConfig.addPassthroughCopy("assets");
  eleventyConfig.addPassthroughCopy("css/theme-syntax-highlighting.css");
  eleventyConfig.addPassthroughCopy({ "node_modules/mermaid/dist/mermaid.min.js": "assets/js/mermaid.min.js" });

  // Preset display: an animated visualizer when docs/assets/frames/<name>.json exists (generated by
  // tools/spritedump), with a static fallback inside it: docs/assets/presets/<name>.(png|gif|webp) if
  // present, otherwise a placeholder that names the file to add. Second argument: hardware profile.
  eleventyConfig.addShortcode("presetShot", function (name, profile = "TextPanel") {
    let fallback = `<figure class="preset-shot preset-shot-empty not-prose"><figcaption>No screenshot yet. Add <code>docs/assets/presets/${name}.png</code>, <code>.gif</code> or <code>.webp</code>.</figcaption></figure>`;
    for (const ext of ["png", "gif", "webp"]) {
      if (fs.existsSync(path.join(__dirname, "assets", "presets", `${name}.${ext}`))) {
        fallback = `<figure class="preset-shot not-prose"><img src="/assets/presets/${name}.${ext}" alt="Screenshot of the ${name} layout" loading="lazy"></figure>`;
        break;
      }
    }
    return `<div class="hv not-prose" data-helm-viz data-layout="${name}" data-profile="${profile}">${fallback}</div>`;
  });

  // Reusable inline block reference. The matrix is decorated after Markdown rendering so its
  // plain-text table remains the source consumed by helm-toolbox/scripts/gen-blocks.js.
  eleventyConfig.addShortcode("blockIcon", function (name) {
    return blockIconMarkup(name);
  });
  eleventyConfig.addTransform("block-icons", function (content) {
    if (!this.page.outputPath || !this.page.outputPath.endsWith("/docs/block-matrix/index.html")) return content;
    for (const name of Object.keys(blockIcons)) {
      const escapedName = escapeHtml(name).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      content = content.replace(new RegExp(`<td([^>]*)>${escapedName}</td>`), `<td$1>${blockIconMarkup(name, "../../assets/")}</td>`);
    }
    return content;
  });

  // Header search index: title, section, description and URL of every doc page, as JSON safe for a <script> tag.
  eleventyConfig.addFilter("searchIndex", function (items) {
    const rows = (items || []).map((i) => ({
      title: i.data.title || "",
      section: i.data.section || "General",
      description: i.data.description || "",
      url: i.url,
    }));
    return JSON.stringify(rows).replace(/</g, "\\u003c");
  });

  // Last-modified date of a source file: last git commit, falling back to the file mtime.
  const modifiedCache = new Map();
  eleventyConfig.addFilter("lastModified", function (inputPath) {
    if (modifiedCache.has(inputPath)) return modifiedCache.get(inputPath);
    const abs = path.resolve(__dirname, inputPath);
    let date = "";
    try {
      date = execFileSync("git", ["-C", REPO_ROOT, "log", "-1", "--format=%cs", "--", abs], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {}
    if (!date) {
      try { date = fs.statSync(abs).mtime.toISOString().slice(0, 10); } catch {}
    }
    modifiedCache.set(inputPath, date);
    return date;
  });

  // Collections
  eleventyConfig.addCollection("docs", function (collectionApi) {
    return collectionApi.getFilteredByTag("docs").sort((a, b) => {
      const orderA = a.data.order !== undefined ? a.data.order : 999;
      const orderB = b.data.order !== undefined ? b.data.order : 999;
      return orderA - orderB;
    });
  });

  // Filter: Group array of doc items by section
  eleventyConfig.addFilter("groupBySection", function (items) {
    if (!items || !Array.isArray(items)) return [];
    const map = new Map();
    for (const item of items) {
      const section = item.data.section || "General";
      if (!map.has(section)) {
        map.set(section, []);
      }
      map.get(section).push(item);
    }
    return Array.from(map.entries()).map(([section, pages]) => ({
      section,
      pages: pages.sort((a, b) => (a.data.order || 999) - (b.data.order || 999))
    }));
  });

  // Filter: Determine active link class
  eleventyConfig.addFilter("isActive", function (pageUrl, currentUrl) {
    if (!pageUrl || !currentUrl) return false;
    return pageUrl === currentUrl || (pageUrl !== "/" && currentUrl.startsWith(pageUrl));
  });

  return {
    pathPrefix: process.env.PAGES_PATH_PREFIX || "/",
    dir: {
      input: ".",
      includes: "_includes",
      output: "../public"
    },
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    templateFormats: ["html", "njk", "md"]
  };
};
