import re,subprocess,collections
src=open('../../Program.cs').read().split('\n')
members=collections.OrderedDict()
open('SeShim.Blocks.cs','w').write('\n')
for it in range(12):
    out=subprocess.run(['dotnet','build','-nologo'],capture_output=True,text=True).stdout
    new=0
    for m in re.finditer(r"Program\.cs\((\d+),(\d+)\): error CS1061: '(\w+)' does not contain a definition for '(\w+)'",out):
        ln,col,t,name=int(m[1]),int(m[2]),m[3],m[4]
        if t=='Vector2?' : continue
        line=src[ln-1]; rest=line[col-1+len(name):col-1+len(name)+1] if False else line[col-1:]
        call=bool(re.match(re.escape(name)+r'\s*(<[^>]*>)?\s*\(',rest))
        k=(t,name)
        if k not in members: members[k]=call; new+=1
    gen=['// Generated by gen.py — dynamic stand-ins for block members Program.cs reads.','using System;','namespace Sandbox.ModAPI.Ingame','{']
    by=collections.OrderedDict()
    for (t,n),c in members.items(): by.setdefault(t,[]).append((n,c))
    for t,ms in by.items():
        gen.append(f'    public partial interface {t}'+'\n    {')
        for n,c in ms:
            gen.append(f'        dynamic {n}(params object[] a);' if c else f'        dynamic {n} {{ get; set; }}')
        gen.append('    }')
    gen.append('}')
    open('SeShim.Blocks.cs','w').write('\n'.join(gen)+'\n')
    print(it,new,len(members))
    if new==0: break
